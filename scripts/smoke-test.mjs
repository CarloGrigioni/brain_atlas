import { chromium } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const browser = await chromium.launch({
  executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe',
  headless: true,
  args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
})
const origin = process.env.TEST_URL ?? 'http://127.0.0.1:5173'
await mkdir('test-results', { recursive: true })
const results = []
try {
  // A motion-free baseline makes exact color round-trip comparisons deterministic.
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  const externalRequests = []
  page.on('request', (request) => { if (!request.url().startsWith(origin) && !request.url().startsWith('data:')) externalRequests.push(request.url()) })
  const response = await page.goto(origin)
  assert.equal(response.status(), 200)
  await page.getByRole('button', { name: 'Reset view', exact: true }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => !document.querySelector('button[aria-label="Reset view"]').disabled, null, { timeout: 60000 })
  assert(await page.getByRole('button', { name: 'Auto-rotate', exact: true }).isDisabled())
  await page.waitForTimeout(2200)
  await page.screenshot({ path: 'test-results/desktop.png' })
  const canvas = page.locator('canvas')
  // Compare the model's central area, excluding overlapping DOM controls and
  // their compositor/antialiasing differences when the checkbox gains focus.
  const box = await canvas.boundingBox()
  const captureModel = () => page.screenshot({ clip: {
    x: box.x + box.width * .15, y: box.y + 80,
    width: box.width * .7, height: box.height - 160,
  } })
  const initial = await captureModel()
  await writeFile('test-results/color-baseline.png', initial)
  const colorToggle = page.getByRole('checkbox', { name: 'Colori anatomici' })
  await colorToggle.check()
  await page.waitForTimeout(200)
  assert(await page.getByRole('list', { name: 'Legenda delle regioni' }).isVisible())
  assert.equal(await page.locator('#anatomy-legend li').count(), 7)
  assert(!initial.equals(await captureModel()), 'Anatomical colors must update the paused scene')
  await page.screenshot({ path: 'test-results/desktop-colors.png' })
  await colorToggle.uncheck()
  await page.waitForTimeout(200)
  assert(!(await page.getByRole('list', { name: 'Legenda delle regioni' }).isVisible()))
  const restored = await captureModel()
  await writeFile('test-results/color-restored.png', restored)
  assert(initial.equals(restored), 'Disabling colors must restore ivory without moving the camera')
  const explodeToggle = page.getByRole('checkbox', { name: 'Esplodi parti' })
  await explodeToggle.check()
  await page.waitForTimeout(200)
  assert.equal(await page.getByRole('slider', { name: 'Separazione' }).inputValue(), '100')
  const exploded = await captureModel()
  assert(!initial.equals(exploded), 'Exploding must separate the rendered parts')
  await colorToggle.check()
  await page.screenshot({ path: 'test-results/desktop-exploded.png' })
  await page.getByRole('slider', { name: 'Separazione' }).focus()
  await page.keyboard.press('ArrowLeft')
  await page.waitForTimeout(200)
  assert.equal(await page.getByRole('slider', { name: 'Separazione' }).inputValue(), '99')
  await page.getByRole('button', { name: 'Ricomponi' }).click()
  await colorToggle.uncheck()
  await page.waitForTimeout(200)
  assert(!(await explodeToggle.isChecked()))
  assert(initial.equals(await captureModel()), 'Recomposition must restore the exact original surface and view')
  await page.getByRole('radio', { name: 'Solo sinistro', exact: true }).check()
  const leftHemisphere = await captureModel()
  assert(!initial.equals(leftHemisphere), 'Showing only the left hemisphere changes the model')
  await page.getByRole('radio', { name: 'Solo destro', exact: true }).check()
  assert(!leftHemisphere.equals(await captureModel()), 'Left and right hemisphere views differ')
  await page.getByRole('radio', { name: 'Entrambi', exact: true }).check()
  assert(initial.equals(await captureModel()), 'Showing both hemispheres restores the original model and camera')
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .65, box.y + box.height * .56, { steps: 20 })
  await page.mouse.up()
  await page.waitForTimeout(500)
  const rotated = await captureModel()
  assert(!initial.equals(rotated), 'Dragging must change the rendered view')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.waitForTimeout(300)
  assert(!rotated.equals(await captureModel()), 'Zoom must change the rendered view')
  await page.getByRole('button', { name: 'Reset view', exact: true }).click()
  await page.waitForTimeout(1600)
  await page.screenshot({ path: 'test-results/desktop-reset.png' })
  await page.getByRole('button', { name: 'Model source and credits' }).click()
  assert(await page.getByRole('dialog').isVisible())
  await page.keyboard.press('Escape')
  assert(!(await page.getByRole('dialog').isVisible()))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(externalRequests, [], 'All runtime assets must be local')
  assert.deepEqual(errors, [], 'No console or runtime errors')
  results.push('Desktop: local GLB, drag rotation, zoom, reset, credits, no console errors, no external runtime requests.')

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  const mobileErrors = []
  mobile.on('pageerror', (error) => mobileErrors.push(error.message))
  await mobile.goto(origin)
  await mobile.waitForFunction(() => !document.querySelector('button[aria-label="Reset view"]').disabled, null, { timeout: 60000 })
  assert(await mobile.getByRole('button', { name: 'Auto-rotate', exact: true }).isDisabled())
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await mobile.screenshot({ path: 'test-results/mobile.png' })
  await mobile.getByRole('checkbox', { name: 'Colori anatomici' }).check()
  await mobile.screenshot({ path: 'test-results/mobile-colors.png' })
  await mobile.getByRole('checkbox', { name: 'Esplodi parti' }).check()
  await mobile.getByRole('radio', { name: 'Solo destro', exact: true }).check()
  await mobile.screenshot({ path: 'test-results/mobile-exploded.png' })
  await mobile.getByRole('radio', { name: 'Solo destro', exact: true }).focus()
  await mobile.keyboard.press('ArrowLeft')
  assert(await mobile.getByRole('radio', { name: 'Solo sinistro', exact: true }).isChecked())
  await mobile.getByRole('radio', { name: 'Entrambi', exact: true }).check()
  await mobile.getByRole('slider', { name: 'Separazione' }).focus()
  await mobile.keyboard.press('ArrowLeft')
  assert.equal(await mobile.getByRole('slider', { name: 'Separazione' }).inputValue(), '99')
  await mobile.getByRole('button', { name: 'Ricomponi' }).click()
  assert(!(await mobile.getByRole('checkbox', { name: 'Esplodi parti' }).isChecked()))
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(mobileErrors, [])
  results.push('Mobile: 390×844, touch-enabled layout, no horizontal overflow, reduced motion disables autorotation.')
  results.push('Anatomical colors: seven-region legend, immediate update while paused, exact ivory restoration without camera movement, mobile layout.')
  results.push('Exploded view: separation, adjustable amount, colors combined with explosion, exact recomposition, mobile and keyboard controls, reduced-motion response.')
  results.push('Hemispheres: left/right visibility, exact restoration of both hemispheres, native keyboard radio selection, compatibility with colors and explosion on mobile.')

  const failure = await browser.newPage()
  await failure.route('**/models/brain.glb', (route) => route.abort())
  await failure.goto(origin)
  await failure.getByRole('heading', { name: 'The view couldn’t be loaded' }).waitFor()
  assert(await failure.getByRole('button', { name: 'Reload model' }).isVisible())
  await failure.unroute('**/models/brain.glb')
  await failure.getByRole('button', { name: 'Reload model' }).click()
  // Retry should clear the cached rejected loader promise as well as the error boundary.
  await failure.waitForFunction(() => !document.querySelector('button[aria-label="Reset view"]').disabled, null, { timeout: 60000 })
  results.push('Loading error: visible failure message and successful recovery after retry.')
  await writeFile('test-results/verification.json', JSON.stringify({ results, errors, externalRequests }, null, 2))
  console.log(results.join('\n'))
} finally {
  await browser.close()
}
